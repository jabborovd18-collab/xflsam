export function t(key, lang = 'uz') {
  const currentLang = translations[lang] || translations.uz;
  const keys = key.split('.');
  let result = currentLang;
  for (const k of keys) {
    if (result && typeof result === 'object' && k in result) {
      result = result[k];
    } else {
      // Fallback to Uzbek if translation missing
      let fallback = translations.uz;
      for (const fk of keys) {
        if (fallback && typeof fallback === 'object' && fk in fallback) {
          fallback = fallback[fk];
        } else {
          return key;
        }
      }
      return fallback;
    }
  }
  return result;
}

export function getTranslations(lang = 'uz') {
  return translations[lang] || translations.uz;
}

